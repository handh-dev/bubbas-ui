import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { chromium } from 'playwright';
process.chdir(new URL('..', import.meta.url).pathname);
const files = { search:'lucide/search', menu:'lucide/menu', close:'lucide/x', sparkles:'lucide/sparkles', pause:'lucide/pause', play:'lucide/play', arrowRight:'lucide/arrow-right', instagram:'simple-icons/instagram', facebook:'simple-icons/facebook', x:'simple-icons/x', youtube:'simple-icons/youtube', tiktok:'simple-icons/tiktok', spotify:'simple-icons/spotify' };
let browser;
try {
 browser=await chromium.launch();
 const page=await browser.newPage({viewport:{width:96,height:96},deviceScaleFactor:1});
 const sources = {}, manifest = {};
 for (const [name, file] of Object.entries(files)) {
  const input = `packages/ui/icons/${file}.svg`;
  // Render the preserved vector at 4x. RN Image needs no native SVG peer or font.
  const vector=readFileSync(input,'utf8').replaceAll('currentColor','#000000');
  await page.setContent(`<style>html,body{margin:0;background:transparent}svg{width:96px;height:96px;display:block}</style>${vector}`);
  const png=await page.screenshot({omitBackground:true});
  sources[name] = 'data:image/png;base64,' + png.toString('base64');
  manifest[name] = { source: file + '.svg', sourceSha256: createHash('sha256').update(readFileSync(input)).digest('hex'), pngSha256:createHash('sha256').update(png).digest('hex'), width:96, height:96 };
 }
 writeFileSync('packages/ui/src/internal/icon-sources.ts', '// Generated by scripts/build-icons.mjs from pinned licensed vectors.\nexport const iconSources = ' + JSON.stringify(sources, null, 2) + ' as const;\n');
 writeFileSync('packages/ui/icons/manifest.json', JSON.stringify({ lucide:'lucide-static@1.61.0', simpleIcons:'simple-icons@16.35.0', rasterizer:'Playwright bundled Chromium '+browser.version(), icons:manifest }, null, 2)+'\n');
} finally { await browser?.close(); }
await import('./verify-icons.mjs');
